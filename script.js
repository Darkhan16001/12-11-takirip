function renderVideo() {
  const container =
    document.getElementById("videoContainer");

  if (!container) return;

  container.innerHTML = videoPlayerHTML();

  document.querySelectorAll("[data-video]")
    .forEach(button => {
      button.classList.toggle(
        "active",
        button.dataset.video === videoMode
      );
    });

  const nativeVideo =
    document.getElementById("railwayVideo");

  if (nativeVideo) {
    nativeVideo.addEventListener("error", () => {
      const status =
        document.getElementById("videoStatus");

      if (status) {
        status.textContent =
          "Видеоны жүктеу мүмкін болмады. " +
          "Басқа бейнесабақты немесе " +
          "интерактивті түсіндірмені таңдаңдар.";
      }
    }, true);
  }
}

function changeSlide(direction) {
  currentSlide =
    (currentSlide + direction + lessonSlides.length) %
    lessonSlides.length;

  renderVideo();
}

