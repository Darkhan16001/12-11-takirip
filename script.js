function commonsImage(file) {
  return (
    "https://commons.wikimedia.org/wiki/Special:FilePath/" +
    encodeURIComponent(file) +
    "?width=1200"
  );
}

function commonsPage(file) {
  return (
    "https://commons.wikimedia.org/wiki/File:" +
    encodeURIComponent(file)
  );
}

