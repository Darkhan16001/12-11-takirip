function pickStudent() {
  const input =
    document.getElementById("studentNames");

  if (!input) return;

  const text = input.value.trim();

  if (!text) {
    document.getElementById("studentResult")
      .textContent =
      "Алдымен студенттердің есімдерін енгізіңдер.";

    return;
  }

  if (text !== studentNamesText) {
    studentNamesText = text;
    remainingStudents = [];
  }

  if (remainingStudents.length === 0) {
    remainingStudents = studentNamesText
      .split(/[,;\n]+/)
      .map(name => name.trim())
      .filter(Boolean);
  }

  if (remainingStudents.length === 0) return;

  const randomIndex = Math.floor(
    Math.random() * remainingStudents.length
  );

  const selected = remainingStudents.splice(
    randomIndex,
    1
  )[0];

  document.getElementById("studentResult")
    .textContent =
    "Таңдалған студент: " + selected;
}

