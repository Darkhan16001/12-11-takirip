function renderNavigation() {
  document.getElementById("stageNavigation").innerHTML =
    stages.map((stage, index) => `
      <button
        class="stage-button ${
          index === currentStage ? "active" : ""
        }"
        data-stage="${index}"
      >
        <span>
          ${index + 1}. ${stage.name}
        </span>

        <small>
          ${stage.minutes} мин
        </small>

      </button>
    `).join("");
}

