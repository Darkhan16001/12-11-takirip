// 20. БАРЛЫҚ БАТЫРМАЛАР
// =============================================

document.addEventListener("click", function(event) {

  // Сабақ кезеңін таңдау

  const stageButton =
    event.target.closest("[data-stage]");

  if (stageButton) {
    showPage(
      Number(stageButton.dataset.stage)
    );

    return;
  }

  // Жауапты ашу немесе жасыру

  const revealButton =
    event.target.closest("[data-reveal]");

  if (revealButton) {
    const answer =
      document.getElementById(
        revealButton.dataset.reveal
      );

    if (!answer) return;

    answer.classList.toggle("visible");

    revealButton.textContent =
      answer.classList.contains("visible")
        ? "Жауапты жасыру"
        : "Жауабын көрсету";

    return;
  }

  // Ұпай қосу және қайтарып алу

  const awardControl =
    event.target.closest("[data-award]");

  if (awardControl) {
    const [team, key, points] =
      awardControl.dataset.award.split("|");

    toggleAward(
      Number(team),
      key,
      Number(points)
    );

    return;
  }

  // Кездейсоқ студент таңдау

  if (event.target.closest("#pickStudent")) {
    pickStudent();
    return;
  }

  // Видео режимдерін ауыстыру

  const videoButton =
    event.target.closest("[data-video]");

  if (videoButton) {
    videoMode = videoButton.dataset.video;
    currentSlide = 0;

    renderVideo();
    return;
  }

  // Интерактивті түсіндірме слайдтары

  const slideButton =
    event.target.closest("[data-slide]");

  if (slideButton) {
    changeSlide(
      Number(slideButton.dataset.slide)
    );

    return;
  }
});

