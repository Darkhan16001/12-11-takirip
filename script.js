// Қайта басылса, ұпай қайтарылады.

const STORAGE_KEY =
  "darkhan-history-11-12-scores";

let awards = [{}, {}, {}];

try {
  const stored = JSON.parse(
    localStorage.getItem(STORAGE_KEY)
  );

  if (
    Array.isArray(stored) &&
    stored.length === 3 &&
    stored.every(
      item =>
        item !== null &&
        typeof item === "object" &&
        !Array.isArray(item)
    )
  ) {
    awards = stored;
  }
} catch (error) {
  awards = [{}, {}, {}];
}

function saveScores() {
  try {
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify(awards)
    );
  } catch (error) {
    // Браузерде сақтау өшірілген
    // жағдайда да ойын жұмыс істейді.
  }
}

function teamScore(index) {
  return Object.values(awards[index]).reduce(
    (sum, value) =>
      sum + (Number.isFinite(value) ? value : 0),
    0
  );
}

function updateScoreboard() {
  document.getElementById("scoreboard").innerHTML =
    awards.map((_, index) => `
      <div class="score-row">
        <span>${index + 1}-команда</span>

        <strong>
          ${teamScore(index)} ұпай
        </strong>
      </div>
    `).join("");

  if (currentStage === 7) {
    renderFinalScores();
  }
}

function awardButton(teamIndex, key, points) {
  const active = Boolean(
    awards[teamIndex][key]
  );

  return `
    <button
      class="award ${active ? "active" : ""}"
      data-award="${teamIndex}|${key}|${points}"
    >
      ${active ? "✓ Ұпай берілді" : "+" + points + " ұпай"}
    </button>
  `;
}

function refreshAwardButtons() {
  document.querySelectorAll("[data-award]")
    .forEach(button => {

      const [team, key, points] =
        button.dataset.award.split("|");

      const active = Boolean(
        awards[Number(team)][key]
      );

      button.classList.toggle(
        "active",
        active
      );

      button.textContent = active
        ? "✓ Ұпай берілді"
        : "+" + points + " ұпай";
    });
}

function toggleAward(teamIndex, key, points) {
  if (!awards[teamIndex]) return;

  if (awards[teamIndex][key]) {
    delete awards[teamIndex][key];
  } else {
    awards[teamIndex][key] = points;
  }

  saveScores();
  refreshAwardButtons();
  updateScoreboard();
}

function resetScores() {
  if (!confirm("Барлық ұпайларды нөлдейміз бе?")) {
    return;
  }

  awards = [{}, {}, {}];

  saveScores();
  refreshAwardButtons();
  updateScoreboard();
}

document.getElementById("resetScores")
  .addEventListener("click", resetScores);

