const TOTAL_MS = TOTAL_MINUTES * 60000;

let savedElapsed = 0;
let startedAt = null;
let timerInterval = null;

function getElapsed() {
  if (startedAt === null) {
    return savedElapsed;
  }

  return savedElapsed + Date.now() - startedAt;
}

function formatTime(milliseconds) {
  const totalSeconds =
    Math.floor(milliseconds / 1000);

  const minutes =
    Math.floor(totalSeconds / 60);

  const seconds =
    totalSeconds % 60;

  return (
    String(minutes).padStart(2, "0") +
    ":" +
    String(seconds).padStart(2, "0")
  );
}

function updateTimer() {
  const elapsed = Math.min(
    getElapsed(),
    TOTAL_MS
  );

  const remaining = Math.max(
    TOTAL_MS - elapsed,
    0
  );

  document.getElementById("timer").textContent =
    formatTime(elapsed);

  document.getElementById("timeRemaining").textContent =
    remaining > 0
      ? "Қалғаны: " + formatTime(remaining)
      : "80 минут аяқталды";

  if (remaining === 0 && startedAt !== null) {
    pauseTimer();
  }
}

function startTimer() {
  if (startedAt !== null) return;

  if (savedElapsed >= TOTAL_MS) {
    savedElapsed = 0;
  }

  startedAt = Date.now();

  timerInterval =
    setInterval(updateTimer, 500);

  updateTimer();
}

function pauseTimer() {
  if (startedAt === null) return;

  savedElapsed = Math.min(
    getElapsed(),
    TOTAL_MS
  );

  startedAt = null;

  clearInterval(timerInterval);
  timerInterval = null;

  updateTimer();
}

function resetTimer() {
  pauseTimer();

  savedElapsed = 0;

  updateTimer();
}

document.getElementById("timerStart")
  .addEventListener("click", startTimer);

document.getElementById("timerPause")
  .addEventListener("click", pauseTimer);

document.getElementById("timerReset")
  .addEventListener("click", resetTimer);

