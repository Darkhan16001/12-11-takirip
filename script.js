// 18. БЕТТЕР АРАСЫНДА АУЫСУ
// =============================================

function showPage(index) {
  if (index < 0 || index >= pages.length) {
    return;
  }

  // Ескі бет DOM-нан алынады.
  // Бейнені басқа бетке ауысқанда тоқтатады.

  currentStage = index;

  document.getElementById("content").innerHTML =
    pages[index]();

  document.getElementById("stageName").textContent =
    stages[index].name;

  document.getElementById("pageNumber").textContent =
    `${index + 1} / ${pages.length}`;

  document.getElementById("progressBar").style.width =
    ((index + 1) / pages.length * 100) + "%";

  document.getElementById("previousButton").disabled =
    index === 0;

  document.getElementById("nextButton").disabled =
    index === pages.length - 1;

  document.getElementById("nextButton").textContent =
    index === pages.length - 2
      ? "Қорытындыға өту →"
      : "Келесі бет →";

  renderNavigation();

  if (index === 3) {
    renderVideo();
  }

  if (index === 5) {
    const input = document.getElementById("studentNames");

    if (input) {
      input.value = studentNamesText;
    }
  }

  if (index === 6) {
    refreshAwardButtons();
  }

  if (index === 7) {
    renderFinalScores();
  }

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

